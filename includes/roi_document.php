<h2>Entraînements</h2>
<ol>
<li>L’échauffement au sol est obligatoire.</li>
<li>La tenue doit être sportive et les baskets de sport sont obligatoires, les autres chaussures ne sont pas admises.</li>
<li>Le port du jeans, de manteaux, d’écharpe ou tout autre vêtement entravant les mouvements sur glace est interdit.</li>
<li>L’accès autour de la patinoire est interdit à toute personne qui n’est pas un.e patineur.se.</li>
<li>Aucun gsm ou smartphone ne sera admis à l’échauffement ainsi que pendant les entraînements. Ils peuvent être déposés à la table du comité. Nous déclinons toutes responsabilités en cas de vol ou de perte.</li>
<li>Le port des gants est obligatoire durant les entraînements sauf exception (compétition ou démonstration ou toute autre autorisation donnée par le professeur).</li>
<li>Les cheveux doivent toujours être attachés (ne pas porter de pince par précaution en cas de chute !)</li>
<li>À la fin de l’entraînement, le vestiaire ainsi que le bord de piste doivent être dans un état impeccable.</li>
<li>Durant les entraînements, l’accès au vestiaire sera interdit sauf autorisation du professeur.</li>
<li>Le club décline toute responsabilité en cas de vol dans le vestiaire ou tout autre endroit de la patinoire.</li>
<li>Seules les personnes du comité sont responsables pour la distribution des patins de location.</li>
<li>À la fin de l’entraînement, si les parents ne sont pas encore arrivés, l’enfant remontera automatiquement à la cafétéria.</li>
</ol>
